/**
 * Builds the demo as a static site for GitHub Pages, into ./out.
 *
 *   NEXT_BASE_PATH=/Brittany-Niemi-Rescues node scripts/build-pages.mjs
 *
 * Static sites can't run server code, so during the build:
 *  - server-only files (login proxy, photo routes, calendar download, password reset links) are set aside;
 *  - each server-actions file ("use server") is replaced by a stand-in with the same exports
 *    that just throws. Demo mode never calls them; it uses the browser-only demo store instead.
 * Everything is put back afterwards, so the regular build is unaffected.
 */
import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, readdirSync, readFileSync, renameSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

const SERVER_ONLY = [
  "src/proxy.ts",
  "src/app/auth/confirm/route.ts",
  "src/app/admin/upload/route.ts",
  "src/app/photos/[...path]/route.ts",
  "src/app/admin/(panel)/meetings/[id]/ics/route.ts",
];
const stash = ".pages-stash";

function serverActionFiles(dir = "src") {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) return serverActionFiles(path);
    return /\.tsx?$/.test(name) && /^\s*["']use server["']/.test(readFileSync(path, "utf8")) ? [path] : [];
  });
}

function stubFor(source) {
  const names = [...source.matchAll(/^export async function (\w+)/gm)].map((m) => m[1]);
  return [
    "// Stand-in generated by scripts/build-pages.mjs for the static demo build.",
    "const unavailable = async (..._args: unknown[]): Promise<never> => {",
    '  throw new Error("Not available in the static demo");',
    "};",
    ...names.map((n) => `export const ${n} = unavailable;`),
    "",
  ].join("\n");
}

const moved = [];
function restore() {
  for (const file of moved.splice(0)) {
    renameSync(join(stash, file), file);
  }
  rmSync(stash, { recursive: true, force: true });
}
for (const sig of ["SIGINT", "SIGTERM"]) {
  process.on(sig, () => {
    restore();
    process.exit(1);
  });
}

let status = 1;
try {
  for (const file of SERVER_ONLY) {
    if (!existsSync(file)) continue;
    mkdirSync(dirname(join(stash, file)), { recursive: true });
    renameSync(file, join(stash, file));
    moved.push(file);
  }
  for (const file of serverActionFiles()) {
    const source = readFileSync(file, "utf8");
    mkdirSync(dirname(join(stash, file)), { recursive: true });
    renameSync(file, join(stash, file));
    moved.push(file);
    writeFileSync(file, stubFor(source));
  }
  const res = spawnSync("npx", ["next", "build"], {
    stdio: "inherit",
    env: {
      ...process.env,
      NEXT_PUBLIC_DEMO: "1",
      NEXT_EXPORT: "1",
      // With a static export, Next writes the finished site into the build folder.
      NEXT_DIST_DIR: "out",
    },
  });
  status = res.status ?? 1;
  if (status === 0) {
    // Serve the _next folder as-is (GitHub Pages' Jekyll would hide it).
    writeFileSync("out/.nojekyll", "");
    console.log("\n✓ Static demo built in ./out");
  }
} finally {
  restore();
}
process.exit(status);
